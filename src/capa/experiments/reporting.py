"""Render the human-readable current status and machine-friendly leaderboard."""

from __future__ import annotations

import csv
import io
import json
from pathlib import Path
from typing import Any

from .registry import load_registry


def _read_json(path: Path) -> dict[str, Any]:
    if not path.exists():
        return {}
    value = json.loads(path.read_text(encoding="utf-8"))
    return value if isinstance(value, dict) else {}


def _primary_metric(row: dict[str, Any]) -> tuple[str, float | None]:
    metrics = row.get("metrics") if isinstance(row.get("metrics"), dict) else {}
    primary = metrics.get("primary") if isinstance(metrics.get("primary"), dict) else {}
    if isinstance(primary.get("value"), (int, float)):
        return str(primary.get("name") or "primary"), float(primary["value"])
    for key in ("mean_score", "candidate_mean", "adapter_smoke_mean_score", "train_loss"):
        if isinstance(metrics.get(key), (int, float)):
            return key, float(metrics[key])
    return "", None


def _model_name(row: dict[str, Any]) -> str:
    method = row.get("method") if isinstance(row.get("method"), dict) else {}
    return str(method.get("model_label") or method.get("model") or "unknown")


def render_current(
    *, registry_path: Path, status_path: Path, dataset_root: Path, output_path: Path
) -> None:
    rows = load_registry(registry_path)
    status = _read_json(status_path)
    current_study = str(status.get("current_study") or "")
    study_rows = [row for row in rows if row.get("study_id") == current_study]
    arm_order = status.get("study_arm_order") if isinstance(status.get("study_arm_order"), list) else []
    arm_rank = {str(label): index for index, label in enumerate(arm_order)}
    dataset_cards = [_read_json(path) for path in sorted(dataset_root.glob("*/manifest.json"))]

    lines = [
        "<!-- Generated by pipelines/experiments/registry_cli.py render. -->",
        "# CAPA Current Research Status",
        "",
        "## Objective",
        "",
        str(status.get("objective") or "Not recorded."),
        "",
        "## Active State",
        "",
        f"- Demo default: `{status.get('demo_default', 'unknown')}`",
        f"- Research candidate: `{status.get('research_candidate', 'unknown')}`",
        f"- Current study: `{current_study or 'none'}`",
        f"- Evidence grade: `{status.get('evidence_grade', 'not_assessed')}`",
        "",
        "## Key Result",
        "",
        str(status.get("key_result") or "Not recorded."),
        "",
        "## Dataset Registry",
        "",
        "| Dataset | Role | Cases | Steps | Integrity |",
        "|---|---|---:|---:|---|",
    ]
    for card in dataset_cards:
        stats = card.get("stats") if isinstance(card.get("stats"), dict) else {}
        integrity = card.get("integrity") if isinstance(card.get("integrity"), dict) else {}
        lines.append(
            f"| `{card.get('dataset_id', 'unknown')}` | {card.get('role', '')} | "
            f"{stats.get('cases', '')} | {stats.get('steps', '')} | {integrity.get('status', '')} |"
        )
    if not dataset_cards:
        lines.append("| _none_ | | | | |")

    lines.extend(
        [
            "",
            "## Current Study Results",
            "",
            "| Date | Run | Model | Method | Status | Primary metric | Decision |",
            "|---|---|---|---|---|---:|---|",
        ]
    )
    for row in sorted(
        study_rows,
        key=lambda item: (
            arm_rank.get(_model_name(item), len(arm_rank)),
            str(item.get("date")),
            str(item.get("run_id")),
        ),
    ):
        metric_name, metric_value = _primary_metric(row)
        metric = "" if metric_value is None else f"{metric_name}={metric_value:.6f}"
        decision = row.get("decision") if isinstance(row.get("decision"), dict) else {}
        lines.append(
            f"| {row.get('date', '')} | `{row.get('run_id', '')}` | {_model_name(row)} | "
            f"{row.get('kind', '')} | {row.get('status', '')} | {metric} | {decision.get('outcome', '')} |"
        )
    if not study_rows:
        lines.append("| | _No completed runs registered_ | | | | | |")

    caveats = status.get("caveats") if isinstance(status.get("caveats"), list) else []
    lines.extend(["", "## Current Caveats", ""])
    lines.extend(f"- {item}" for item in caveats)
    if not caveats:
        lines.append("- None recorded.")
    lines.extend(["", "## Next Decision", "", str(status.get("next_decision") or "Not recorded."), ""])
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text("\n".join(lines), encoding="utf-8")


def render_leaderboard(*, registry_path: Path, output_path: Path) -> None:
    rows = load_registry(registry_path)
    buffer = io.StringIO()
    fieldnames = [
        "date",
        "study_id",
        "run_id",
        "model",
        "kind",
        "status",
        "dataset_id",
        "split",
        "metric_name",
        "metric_value",
        "decision",
    ]
    writer = csv.DictWriter(buffer, fieldnames=fieldnames, lineterminator="\n")
    writer.writeheader()
    for row in sorted(rows, key=lambda item: (str(item.get("date")), str(item.get("run_id")))):
        metric_name, metric_value = _primary_metric(row)
        if metric_value is None:
            continue
        data = row.get("data") if isinstance(row.get("data"), dict) else {}
        decision = row.get("decision") if isinstance(row.get("decision"), dict) else {}
        writer.writerow(
            {
                "date": row.get("date", ""),
                "study_id": row.get("study_id", ""),
                "run_id": row.get("run_id", ""),
                "model": _model_name(row),
                "kind": row.get("kind", ""),
                "status": row.get("status", ""),
                "dataset_id": data.get("dataset_id", ""),
                "split": data.get("split", ""),
                "metric_name": metric_name,
                "metric_value": f"{metric_value:.9f}",
                "decision": decision.get("outcome", ""),
            }
        )
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(buffer.getvalue(), encoding="utf-8")
